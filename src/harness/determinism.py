"""The determinism shim: one set of controls, injected identically into both
versions under test.

Injected as `sitecustomize.py` on `PYTHONPATH`, so it runs before the target is
imported and cannot be skipped by the target. `PYTHONHASHSEED=0` is the one
control that must be in the *environment* rather than the shim, because Python
reads it before any of our code runs.

**Per-case reset.** `reset_controls()` reseeds `random` and rewinds the UUID
counter before every case. Without it a case's result depends on what earlier
cases consumed, the A/A baseline (which uses one case order) cannot see that
coupling, and a refactor that changes how many random/uuid calls one case makes
would shift every later case and produce a flood of false "different" results.

**Clock coverage.** CPython's `time.localtime()`, `gmtime()`, `ctime()` and
no-argument `strftime()` read the C clock directly; patching `time.time` alone
does not affect them. They are patched explicitly here, and the probe prints
each one so the report can say which controls actually applied.
"""

from __future__ import annotations

import os
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

SHIM_MODULE = "sitecustomize"

# Deterministic instants. 1700000000 = 2023-11-14T22:13:20Z.
FROZEN_EPOCH = 1700000000.0
FROZEN_UUID_NAMESPACE = 0x5EED0000000000000000000000000000

SHIM_TEMPLATE = f'''\
"""Generated by harness.determinism - do not edit in place."""

import datetime as _dt
import os as _os
import random as _random
import time as _time
import uuid as _uuid

_CONTROLS = []

# A control can be switched off for an experiment (`HARNESS_SHIM_DISABLE`), so
# the "controls applied" list in a report is what actually ran rather than what
# the shim intended to run.
_DISABLED = frozenset(
    entry.strip()
    for entry in _os.environ.get("HARNESS_SHIM_DISABLE", "").split(",")
    if entry.strip()
)


def _on(name):
    return name not in _DISABLED


_FROZEN_EPOCH = __FROZEN_EPOCH__

# The serializer must keep recognising values the target returns AFTER we
# replace the module attributes, so the originals are kept reachable.
ORIGINAL_DATETIME = _dt.datetime
ORIGINAL_DATE = _dt.date
ORIGINAL_TIME = _dt.time

_REAL_TIME = {{
    name: getattr(_time, name)
    for name in ("time", "time_ns", "monotonic", "perf_counter", "localtime",
                 "gmtime", "ctime", "strftime")
    if hasattr(_time, name)
}}


class _FrozenDateTime(_dt.datetime):
    @classmethod
    def now(cls, tz=None):
        base = _dt.datetime.fromtimestamp(_FROZEN_EPOCH, tz=_dt.timezone.utc)
        return base if tz else base.replace(tzinfo=None)

    @classmethod
    def utcnow(cls):
        return _dt.datetime.fromtimestamp(_FROZEN_EPOCH, tz=_dt.timezone.utc).replace(tzinfo=None)

    @classmethod
    def today(cls):
        return cls.now()


class _FrozenDate(_dt.date):
    @classmethod
    def today(cls):
        # date.fromtimestamp takes no tz kwarg; TZ=UTC makes this the frozen day
        return _dt.date.fromtimestamp(_FROZEN_EPOCH)


if _on("clock_frozen"):
    _dt.datetime = _FrozenDateTime  # type: ignore[misc]
    _dt.date = _FrozenDate  # type: ignore[misc]
    _CONTROLS.append("clock_frozen")

# time.time() and friends. localtime/gmtime/ctime/strftime read the C clock when
# called with no argument, so they are patched explicitly rather than assumed.
if _on("time_time_frozen"):
    _time.time = lambda: _FROZEN_EPOCH  # type: ignore[assignment]
    if hasattr(_time, "time_ns"):
        _time.time_ns = lambda: int(_FROZEN_EPOCH * 1_000_000_000)  # type: ignore[assignment]
    _CONTROLS.append("time_time_frozen")

_FROZEN_STRUCT = _REAL_TIME["localtime"](_FROZEN_EPOCH)
_FROZEN_TUPLE = _REAL_TIME["gmtime"](_FROZEN_EPOCH)


def _localtime(secs=None):
    return _FROZEN_STRUCT if secs is None else _REAL_TIME["localtime"](secs)


def _gmtime(secs=None):
    return _FROZEN_TUPLE if secs is None else _REAL_TIME["gmtime"](secs)


def _ctime(secs=None):
    return _REAL_TIME["ctime"](_FROZEN_EPOCH if secs is None else secs)


def _strftime(fmt, t=None):
    return _REAL_TIME["strftime"](fmt, _FROZEN_TUPLE if t is None else t)


if _on("struct_time_frozen"):
    _time.localtime = _localtime  # type: ignore[assignment]
    _time.gmtime = _gmtime  # type: ignore[assignment]
    _time.ctime = _ctime  # type: ignore[assignment]
    _time.strftime = _strftime  # type: ignore[assignment]
    _CONTROLS.append("struct_time_frozen")

# Monotonic counters are frozen rather than counted: a counter would still make
# a value depend on how many calls the target makes, which is exactly the
# coupling per-case reset is meant to remove.
if _on("monotonic_frozen"):
    _time.monotonic = lambda: 0.0  # type: ignore[assignment]
    _time.perf_counter = lambda: 0.0  # type: ignore[assignment]
    if hasattr(_time, "monotonic_ns"):
        _time.monotonic_ns = lambda: 0  # type: ignore[assignment]
    if hasattr(_time, "perf_counter_ns"):
        _time.perf_counter_ns = lambda: 0  # type: ignore[assignment]
    _CONTROLS.append("monotonic_frozen")

if _on("random_seeded"):
    _random.seed(0)
    _CONTROLS.append("random_seeded")

_counter = {{"n": 0}}


def _uuid4():
    _counter["n"] += 1
    return _uuid.UUID(int={FROZEN_UUID_NAMESPACE} + _counter["n"])


def _uuid1(node=None, clock_seq=None):
    return _uuid4()


if _on("uuid_frozen"):
    _uuid.uuid4 = _uuid4  # type: ignore[assignment]
    _uuid.uuid1 = _uuid1  # type: ignore[assignment]
    _CONTROLS.append("uuid_frozen")


def reset_controls():
    """Per-case reset: the SAME starting state for every case.

    Without this, `random` and the uuid counter carry over between cases, so a
    result depends on what earlier cases consumed and a refactor that changes
    the call count shifts every later case.
    """
    if not _on("per_case_reset"):
        return
    _random.seed(0)
    _counter["n"] = 0


if _on("per_case_reset"):
    _CONTROLS.append("per_case_reset")

if _os.environ.get("PYTHONHASHSEED") == "0" and _on("hash_seed_0"):
    _CONTROLS.append("hash_seed_0")
if _os.environ.get("TZ") == "UTC" and _on("tz_utc"):
    try:
        _time.tzset()  # type: ignore[attr-defined]
    except AttributeError:
        pass
    _CONTROLS.append("tz_utc")
if (_os.environ.get("LC_ALL") or "").startswith("C.UTF-8") and _on("locale_c"):
    _CONTROLS.append("locale_c")
if _os.environ.get("HARNESS_CWD_FIXED") == "1" and _on("cwd_fixed"):
    _CONTROLS.append("cwd_fixed")
if _os.environ.get("HARNESS_ENV_SCRUBBED") == "1" and _on("env_scrubbed"):
    _CONTROLS.append("env_scrubbed")

CONTROLS = tuple(_CONTROLS)
'''

# The probe names one clock surface per line, so a report can say which ones the
# shim actually controls instead of asserting that it controls "the clock".
PROBE_LINES: tuple[tuple[str, str], ...] = (
    ("time.time", "time.time()"),
    ("time.time_ns", "time.time_ns()"),
    ("time.monotonic", "time.monotonic()"),
    ("time.perf_counter", "time.perf_counter()"),
    ("time.localtime", "time.localtime()"),
    ("time.gmtime", "time.gmtime()"),
    ("time.ctime", "time.ctime()"),
    ("time.strftime", "time.strftime('%Y-%m-%d %H:%M:%S')"),
    ("datetime.now", "datetime.datetime.now().isoformat()"),
    ("datetime.utcnow", "datetime.datetime.utcnow().isoformat()"),
    ("date.today", "datetime.date.today().isoformat()"),
    ("random", "random.random()"),
    ("uuid4", "uuid.uuid4()"),
    ("hash", "hash('x')"),
)


def shim_source(epoch: float = FROZEN_EPOCH) -> str:
    """The shim's source, frozen at `epoch`.

    The epoch is a parameter so an experiment can move the clock a year and show
    WHICH cases read it: two same-epoch runs agree even for time-dependent cases,
    so agreement alone proves nothing about the clock control.
    """
    return SHIM_TEMPLATE.replace("__FROZEN_EPOCH__", repr(epoch))


SHIM_SOURCE = shim_source()


def shim_controls() -> list[str]:
    """The control names the shim applies, in the order it reports them."""
    return [
        "clock_frozen",
        "time_time_frozen",
        "struct_time_frozen",
        "monotonic_frozen",
        "random_seeded",
        "uuid_frozen",
        "per_case_reset",
        "hash_seed_0",
        "tz_utc",
        "locale_c",
        "cwd_fixed",
        "env_scrubbed",
    ]


def write_shim(directory: Path, epoch: float = FROZEN_EPOCH) -> Path:
    """Write `sitecustomize.py` into `directory`; return the directory."""
    directory.mkdir(parents=True, exist_ok=True)
    (directory / f"{SHIM_MODULE}.py").write_text(shim_source(epoch), encoding="utf-8")
    return directory


def child_env(
    checkout: Path,
    shim_dir: Path,
    pythonpath: list[Path],
    shim_disable: Sequence[str] = (),
) -> dict[str, str]:
    """The minimal, identical environment both versions run under.

    Allowlist, not a copy: the parent's environment is the harness's, and
    leaking it into the child would make the two runs differ for reasons that
    have nothing to do with the target.
    """
    entries = [str(shim_dir), str(checkout), *(str(path) for path in pythonpath)]
    env = {
        "PYTHONPATH": os.pathsep.join(entries),
        "PYTHONHASHSEED": "0",  # must be in the environment: read before our code
        "TZ": "UTC",
        "LC_ALL": "C.UTF-8",
        "LANG": "C.UTF-8",
        "PYTHONIOENCODING": "utf-8",
        "PYTHONDONTWRITEBYTECODE": "1",
        "HARNESS_CWD_FIXED": "1",
        "HARNESS_ENV_SCRUBBED": "1",
        "HOME": str(checkout),
        "PATH": os.environ.get("PATH", ""),
    }
    if shim_disable:
        env["HARNESS_SHIM_DISABLE"] = ",".join(shim_disable)
    if sys.platform == "win32":
        # Windows needs these to start a working interpreter at all
        for name in ("SYSTEMROOT", "TEMP", "TMP", "USERPROFILE"):
            if name in os.environ:
                env[name] = os.environ[name]
    return env


def probe_script() -> str:
    """The self-test: every clock surface and every stochastic control."""
    # The probe must also run with NO shim: that is the control arm, and without
    # it "the shim controls this surface" would be an unfalsifiable claim. So the
    # import is optional and the reset loop only runs when a shim is present.
    body = [
        "import datetime, hashlib, random, time, uuid",
        "try:",
        "    import sitecustomize",
        "except ModuleNotFoundError:",
        "    sitecustomize = None",
        "if sitecustomize is not None:",
        "    for _ in range(2):",
        "        print('reset', sitecustomize.reset_controls())",
    ]
    for name, call in PROBE_LINES:
        body.append(f"print({name!r}, {call})")
    body.append(
        "print('controls', ','.join(sitecustomize.CONTROLS) if sitecustomize else '')"
    )
    return "\n".join(body) + "\n"


def parse_probe(stdout: str) -> dict[str, str]:
    """`{surface: value}` from the probe output (the report's evidence)."""
    values: dict[str, str] = {}
    for line in stdout.splitlines():
        if " " not in line:
            continue
        name, value = line.split(" ", 1)
        values[name] = value
    return values


def run_probe(
    python: str, checkout: Path, shim_dir: Path, pythonpath: list[Path]
) -> dict[str, Any]:
    """Run the probe once and return its stdout plus the controls it applied."""
    import subprocess

    env = child_env(checkout, shim_dir, pythonpath)
    result = subprocess.run(
        [python, "-c", probe_script()],
        cwd=str(checkout),
        env=env,
        capture_output=True,
        text=True,
        timeout=120,
    )
    controls = ""
    for line in result.stdout.splitlines():
        if line.startswith("controls "):
            controls = line.split(" ", 1)[1]
    return {
        "stdout": result.stdout,
        "stderr": result.stderr,
        "returncode": result.returncode,
        "controls": tuple(controls.split(",")) if controls else (),
    }
